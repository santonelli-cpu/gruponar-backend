// Compatibilidad con el resto del código, que ya usaba SCENARIOS[key].label
// / .labelShort / .badgeClass / .sellerTypes / .buyerTypes en muchos
// lugares — en vez de tocar cada uno de esos usos, SCENARIOS queda como un
// proxy que resuelve el idioma actual en el momento de leer la propiedad.
const SCENARIOS = new Proxy(SCENARIOS_I18N, {
  get(target, scenarioKey){
    const entry = target[scenarioKey];
    if(!entry) return undefined;
    const i18n = entry[lang] || entry.es;
    return { label: i18n.label, labelShort: i18n.labelShort, badgeClass: entry.badgeClass, sellerTypes: entry.sellerTypes, buyerTypes: entry.buyerTypes };
  }
});

