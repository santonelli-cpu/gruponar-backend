// Selector de idioma — persistido en localStorage, aplica a toda la SPA
// (no a los machotes de KYC/contrato, que ya eligen idioma por su cuenta
// vía el selector propio de cada expediente). `t()` es el helper de
// traducción: busca la clave en STRINGS[lang], cae a STRINGS.es si falta,
// y por último a la clave misma (para no romper si falta una traducción).
let lang = localStorage.getItem('nar_lang') || 'es';
function t(key, vars){
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.es[key] ?? key;
  if(vars) Object.keys(vars).forEach(k => { s = s.replace(new RegExp('\\{'+k+'\\}','g'), vars[k]); });
  return s;
}

